import test from 'node:test';
import assert from 'node:assert/strict';
import {initialNotebook,addStudent,addAssessment,createRubric,setRubricGrade,setItacaAttitudeCondition,setItacaGroupRule,setPeriodCategory,setFinalConfig,setGradeObservation,setCategoryColumnColor,rolloverAcademicYear,ACADEMIC_ROLLOVER_OPTIONS,academicSubjectAccent,assertModel} from '../src/model.js';
import {saveSlot,activeYear} from '../src/planner.js';
const all=()=>Object.fromEntries(ACADEMIC_ROLLOVER_OPTIONS.map(([k])=>[k,true]));
const request=options=>({sourceCourse:'2026-2027',name:'2027-2028',start:'2027-09-01',end:'2028-06-30',options});
test('rollover preserves historical data, remaps references and excludes personal data',()=>{
 const d=initialNotebook(),g=d.groups[0],p=d.periods[0],a=d.categories.find(c=>c.name==='Actitud');
 const r=createRubric(d,'Actitud docente',[{name:'Trabajo',maxScore:10,weight:1}]);
 const activity=addAssessment(d,{name:'Actitud con rúbrica',groupId:g.id,periodId:p.id,categoryId:a.id,rubricId:r.id});
 setRubricGrade(d,d.students[0].id,activity.id,{[r.criteria[0].id]:8});
 setGradeObservation(d,d.students[0].id,activity.id,'Observación privada');
 setItacaGroupRule(d,g.id,'seven');
 setItacaAttitudeCondition(d,g.id,p.id,{mode:'criterion',categoryId:a.id,minScore:5,assessmentId:activity.id,criterionId:r.criteria[0].id});
 setPeriodCategory(d,g.id,p.id,a.id,{weight:25,rule:'mean',bestCount:2});
 setFinalConfig(d,g.id,{rule:'weighted_mean',weights:{[p.id]:2}});
 setCategoryColumnColor(d,a.id,'#AABBCC');
 const original=d.assessments[0];
 addAssessment(d,{name:'Recuperación',groupId:g.id,periodId:p.id,categoryId:original.categoryId,recoveryOf:original.id});
 saveSlot(d,{day:0,start:'08:00',end:'09:00',type:'class',groupId:g.id});
 const before=structuredClone(d);
 const result=rolloverAcademicYear(d,request(all()));
 assert.equal(result.groups,1);assertModel(d);
 const ng=d.groups.find(x=>x.course==='2027-2028');
 assert.notEqual(ng.id,g.id);assert.equal(ng.itacaRounding,'seven');
 for(const k of ['students','grades','gradeObservations','finalOverrides','individualCategoryRules','tutorships','evaluationArchive','periods'])assert.deepEqual(d[k],before[k],k);
 for(const k of ['groups','categories','assessments','rubrics','competencies','gradingProfiles','finalConfigs'])assert.deepEqual(d[k].slice(0,before[k].length),before[k],k);
 assert.deepEqual(d.planner.years[0],before.planner.years[0]);
 const newActivities=d.assessments.filter(a=>a.groupId===ng.id);
 assert.equal(newActivities.length,before.assessments.length);
 const condition=ng.itacaAttitudeConditions[p.id],na=newActivities.find(a=>a.id===condition.assessmentId);
 assert.ok(na);assert.notEqual(na.rubricId,r.id);
 assert.equal(d.rubrics.find(r=>r.id===na.rubricId).criteria[0].id,condition.criterionId);
 assert.equal(d.categories.find(c=>c.id===condition.categoryId).columnColor,'#AABBCC');
 assert.ok(newActivities.some(a=>a.recoveryOf&&newActivities.some(b=>b.id===a.recoveryOf)));
 assert.equal(activeYear(d).slots[0].groupId,ng.id);
 for(const k of ['events','lessons','holidays','exceptions','tasks'])assert.deepEqual(activeYear(d)[k],[]);
 assert.equal(d.finalConfigs.find(c=>c.groupId===ng.id).weights[p.id],2);
 assert.equal(d.competencies.filter(c=>c.groupId===ng.id).length,1);
});
test('invalid dependencies and duplicate destination are atomic',()=>{
 const d=initialNotebook(),before=structuredClone(d);
 assert.throws(()=>rolloverAcademicYear(d,request({...all(),categories:false})));
 assert.deepEqual(d,before);
 rolloverAcademicYear(d,request(all()));
 const after=structuredClone(d);
 assert.throws(()=>rolloverAcademicYear(d,request(all())));
 assert.deepEqual(d,after);
});
test('minimal new course has no copied groups or activities',()=>{
 const d=initialNotebook(),options=Object.fromEntries(ACADEMIC_ROLLOVER_OPTIONS.map(([k])=>[k,false]));
 const before=structuredClone(d);
 rolloverAcademicYear(d,request(options));
 assert.deepEqual(d.groups,before.groups);assert.deepEqual(d.assessments,before.assessments);
 assert.deepEqual(activeYear(d).slots,[]);assertModel(d);
});
test('new group configurations are independent and visual transfer is optional',()=>{
 const d=initialNotebook(),g=d.groups[0],cat=d.categories[0];
 setCategoryColumnColor(d,cat.id,'#AABBCC');d.settings.subjectAccents['1bach:Latín I']='#123456';
 rolloverAcademicYear(d,request({...all(),visual:false}));
 const ng=d.groups.find(g=>g.course==='2027-2028'),nc=d.categories.find(c=>c.ownerGroupId===ng.id&&c.name===cat.name);
 assert.equal(nc.columnColor,undefined);
 assert.equal(academicSubjectAccent(d,'2027-2028','1bach','Latín I'),'#F59E0B');
 setCategoryColumnColor(d,nc.id,'#FFFFFF');
 assert.equal(cat.columnColor,'#AABBCC');assert.equal(d.categories.find(c=>c.id===cat.id).columnColor,'#AABBCC');
 addStudent(d,ng.id,{name:'Alumno nuevo'});
 assertModel(d);
});
