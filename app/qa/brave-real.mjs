import assert from 'node:assert/strict';
import {tab} from './cdp-tab.mjs';
import {mkdir,readdir,readFile,rm,writeFile} from 'node:fs/promises';

const base='http://127.0.0.1:'+(process.env.PORT||4175)+'/';
const password='Cuaderno ficticio de pruebas 2026';
const output=process.argv[2] || '/tmp/cuadernodocente-capturas';
const downloads=output+'/descargas';
await mkdir(downloads,{recursive:true});
await mkdir(output,{recursive:true});


const a=await tab(base,password);
const b=await tab(base,password);
try{
  await a.send('Page.setDownloadBehavior',{behavior:'allow',downloadPath:downloads});
  await a.send('Emulation.setEmulatedMedia',{features:[{name:'prefers-color-scheme',value:'light'}]});
  await a.open();
  assert.equal(await a.run("Boolean(document.querySelector('#confirm-password'))"),true,'Usa un perfil desechable vacío para la prueba.');
  await a.unlock(password,true);
  await a.wait('Boolean(navigator.serviceWorker.controller)');
  assert.equal(await a.run("document.querySelectorAll('.grade-table tbody tr').length"),8);
  const first='.note-input',other='.grade-table tbody tr:nth-child(2) .note-input';
  const originalOther=await a.run(`document.querySelector('${other}').value`);
  await a.edit(first,'0');
  await a.wait("document.querySelector('.note-input').defaultValue==='0'");
  assert.equal(await a.run(`document.querySelector('${other}').value`),originalOther);
  await b.open();await b.unlock();
  await a.edit(first,'7,5');
  await a.wait("document.querySelector('.note-input').defaultValue==='7,5'");
  await b.edit(first,'3');
  await b.wait("document.querySelector('#save-status').textContent.includes('Sin guardar')");
  await b.press('[data-tab=ajustes]');
  assert.equal(await b.run("Boolean(document.querySelector('#backup-draft'))"),true);
  await a.open();await a.unlock('Contraseña incorrecta de pruebas');
  await a.unlock();
  assert.equal(await a.run("document.querySelector('.note-input').value"),'7,5');
  console.log('IndexedDB real: cero, aislamiento, recarga, contraseña incorrecta y conflicto entre dos pestañas.');
  await a.press('[data-tab=ajustes]');
  const backupName='CuadernoDocente-'+new Date().toISOString().slice(0,10)+'.cdoc';
  const backup=downloads+'/'+backupName;
  await rm(backup,{force:true});
  await a.press('#backup-download');
  for(let n=0;n<100&&!(await readdir(downloads)).includes(backupName);n++)await new Promise(ok=>setTimeout(ok,100));
  const encrypted=JSON.parse(await readFile(backup,'utf8'));
  assert.equal(encrypted.format,'CuadernoDocenteEncrypted');
  assert.equal(typeof encrypted.data,'string');
  assert.equal(encrypted.students,undefined);
  await a.press('[data-tab=cuaderno]');
  await a.edit(first,'2');
  await a.wait("document.querySelector('.note-input').defaultValue==='2'");
  await a.press('[data-tab=ajustes]');
  await a.upload('#backup-file',backup);await a.restorePassword();
  await a.wait("document.querySelector('.note-input')?.defaultValue==='7,5'");
  for(const value of ['2','7,5']){
    await a.press('[data-tab=ajustes]');
    await a.press('#backup-recover');await a.restorePassword();
    await a.wait(`document.querySelector('.note-input')?.defaultValue===${JSON.stringify(value)}`);
  }
  console.log('Copia .cdoc descargada, restaurada e intercambiada dos veces con el rescate mediante la interfaz real.');
  await a.press('[data-tab=ajustes]');
  await a.press('#check-offline');
  await a.wait("document.querySelector('#offline-result').textContent.includes('recursos estáticos están en caché')");
  await a.send('Network.enable');
  await a.send('Network.emulateNetworkConditions',{offline:true,latency:0,downloadThroughput:0,uploadThroughput:0});
  await a.open();await a.unlock();
  await a.edit(first,'');
  await a.wait("document.querySelector('.note-input').defaultValue===''");
  await a.open();await a.unlock();
  assert.equal(await a.run("document.querySelector('.note-input').value"),'');
  await a.press('[data-course-choice="2bach"]');
  await a.press('[data-tab=curriculo]');
  await a.wait("document.querySelector('.curr-intro h2')?.textContent.includes('2022')");
  await a.press('[data-curr-section=criterios]');
  assert.equal(await a.run("document.querySelectorAll('.curr-criterion').length"),22);
  await a.press('[data-curr-version="2026"]');
  assert.equal(await a.run("document.querySelectorAll('.curr-competency').length"),5);
  console.log('Service worker real: recarga y desbloqueo sin red, borrado persistente y fichas curriculares.');
  await a.press('[data-tab=cuaderno]');
  const create=async(button,values,form='#modal-form')=>{
    await a.press(button);
    await a.run(`(()=>{const form=document.querySelector(${JSON.stringify(form)});
      for(const [selector,value] of Object.entries(${JSON.stringify(values)}))form.querySelector(selector).value=value;
      form.requestSubmit();return true;})()`);
    await a.wait("!document.querySelector('dialog').open");
  };
  await create('#new-group',{'[name=name]':'Grupo ficticio QA'});
  await create('#new-student',{'[name=name]':'Alumna de prueba'});
  await create('#new-assessment',{'[name=name]':'Análisis sobre cinco','[name=maxScore]':'5'});
  await a.edit(first,'4');
  await a.wait("document.querySelector('.score-button')?.textContent==='8,00'");
  await a.press('[data-tab=rubricas]');
  await create('#create-rubric',{'#rubric-editor-name':'Trabajo QA'},'#rubric-editor');
  await a.press('[data-tab=cuaderno]');
  await a.press('#new-assessment');
  const rubricId=await a.run("document.querySelector('[name=rubricId]').options[1].value");
  await a.run(`(()=>{const form=document.querySelector('#modal-form');form.elements.name.value='Actividad con rúbrica';
    form.elements.rubricId.value=${JSON.stringify(rubricId)};form.requestSubmit();return true;})()`);
  await a.wait("!document.querySelector('dialog').open");
  await a.press('[data-rubric-grade]');
  await a.run(`(()=>{document.querySelectorAll('[data-rating-id]').forEach((input,i)=>{
    input.value=['5','0','2'][i];input.dispatchEvent(new Event('input',{bubbles:true}));
  });return true;})()`);
  await a.wait("document.querySelector('#rubric-live-score').textContent==='7,50 / 10'");
  await a.press('#save-rubric-grade');
  await a.wait("!document.querySelector('dialog').open");
  await a.wait("document.querySelector('.score-button').textContent==='7,75'");
  await a.press('[data-view-student]');
  assert.match(await a.run("document.querySelector('#tab-content').textContent"),/Alumna de prueba/);
  await a.press('[data-tab=final]');
  await a.edit('[data-finalstudent]','0');
  await a.wait("document.querySelector('.final-table strong')?.textContent==='0,00'");
  await a.edit('[data-finalstudent]','');
  await a.wait("document.querySelector('.final-table strong')?.textContent==='7,75'");
  console.log('Sin red: grupo, alumna, escala 0–5, rúbrica de tres criterios, ficha individual y nota anual manual cero o automática.');
  await a.press('[data-course-choice="1bach"]');
  for(const [name,width,height] of [['escritorio',1320,900],['tableta',820,1180],['movil',390,844]]){
    await a.send('Emulation.setDeviceMetricsOverride',{width,height,deviceScaleFactor:1,mobile:width<600});
    await a.press('[data-tab=cuaderno]');
    assert.equal(await a.run('document.documentElement.scrollWidth<=innerWidth'),true);
    assert.equal(await a.run("getComputedStyle(document.querySelector('#save-status')).display!=='none'"),true);
    const shot=await a.send('Page.captureScreenshot',{format:'png'});
    await writeFile(output+'/'+name+'.png',Buffer.from(shot.data,'base64'));
  }
  await a.send('Emulation.setEmulatedMedia',{features:[{name:'prefers-color-scheme',value:'dark'}]});
  await a.wait("getComputedStyle(document.querySelector('.panel')).backgroundColor==='rgb(27, 38, 56)'");
  await writeFile(output+'/movil-oscuro.png',Buffer.from((await a.send('Page.captureScreenshot',{format:'png'})).data,'base64'));
  assert.deepEqual([...a.errors,...b.errors],[]);
  console.log('Sin errores JavaScript no capturados. Capturas en 1320, 820 y 390 px.');
}finally{a.close();b.close();}
